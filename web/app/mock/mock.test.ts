describe('submission visibility', () => {
  const winter = () => contestId('winter-2026')

  async function listSubmissions(): Promise<Submission[]> {
    const res = await call<{ submissions: Submission[] }>(
      'GET',
      `/api/contests/${winter()}/submissions`,
    )
    return res.submissions
  }

  it('gives an administrator full feedback on everyone’s submissions', async () => {
    await signIn('alice@example.com')
    const rows = await listSubmissions()
    // Seeded: alice 3, bob 5, carol 3, frank 1.
    expect(rows.length).toBe(12)
    expect(rows.every((r) => r.feedback === 'full')).toBe(true)
    expect(rows.every((r) => r.entrant_display_name)).toBe(true)
    // A system fault is visible to an administrator, verdict included.
    expect(rows.some((r) => r.verdict === 'system_error')).toBe(true)
  })

  it('gives an organization administrator the same view as the owner', async () => {
    // Bob holds the `admin` role in the organization, which is enough.
    await signIn('bob@example.com')
    expect((await listSubmissions()).length).toBe(12)
  })

  it('shows a contestant their own results and hides everyone else’s', async () => {
    await signIn('carol@example.com')
    const rows = await listSubmissions()
    expect(rows.length).toBe(3)
    expect(rows.every((r) => r.entrant_display_name === 'Carol Wang')).toBe(true)
    expect(rows.some((r) => r.verdict === 'system_error')).toBe(false)
  })

  it('reduces a system fault to a bare verdict, and only for its submitter', async () => {
    // A fault is not a personal result, so it carries no score and no subtasks
    // — just enough for the submitter to see that judging broke.
    await signIn('frank@example.com')
    const mine = await listSubmissions()
    expect(mine.length).toBe(1)
    expect(mine[0]!.verdict).toBe('system_error')
    expect(mine[0]!.score).toBeUndefined()
    expect(mine[0]!.subtasks).toBeUndefined()
    expect(mine[0]!.compile_failed).toBeUndefined()

    await signIn('carol@example.com')
    expect((await listSubmissions()).some((r) => r.verdict === 'system_error')).toBe(false)
  })

  it('does not flag anything as non-effective before a rejudge', async () => {
    await signIn('alice@example.com')
    expect((await listSubmissions()).every((r) => r.not_effective !== true)).toBe(true)
  })
})

