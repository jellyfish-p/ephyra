describe('registration', () => {
  it('accepts an external registrant before the contest starts', async () => {
    await signIn('dave@example.com')
    const created = await call<{ entrant_id: string; status: string }>(
      'POST',
      `/api/contests/${contestId('autumn-acm')}/register`,
    )
    expect(created.status).toBe('accepted')

    const { entrant } = await call<{ entrant: { status: string; members: unknown[] } | null }>(
      'GET',
      `/api/contests/${contestId('autumn-acm')}/my-entrant`,
    )
    expect(entrant?.status).toBe('accepted')
    expect(entrant?.members.length).toBe(1)

    await expectFailure(
      () => call('POST', `/api/contests/${contestId('autumn-acm')}/register`),
      409,
      'conflict',
    )
  })

  it('refuses registration after the contest has ended', async () => {
    // Registration stays open for the whole contest, so only an ended contest
    // closes it.
    await signIn('dave@example.com')
    await expectFailure(
      () => call('POST', `/api/contests/${contestId('summer-ioi')}/register`),
      409,
      'conflict',
    )
  })

  it('refuses individual registration in a team contest', async () => {
    await signIn('frank@example.com')
    await expectFailure(
      () => call('POST', `/api/contests/${contestId('spring-oi')}/register`),
      409,
      'conflict',
    )
  })

  it('queues a team for review and lets an administrator accept it', async () => {
    await signIn('alice@example.com')
    const spring = contestId('spring-oi')
    const { entrants } = await call<{
      entrants: { id: string; display_name: string; status: string }[]
    }>('GET', `/api/contests/${spring}/entrants`, { query: { status: 'pending' } })
    expect(entrants.length).toBe(2)

    const team = entrants.find((e) => e.display_name === 'Team Rocket')!
    await call('POST', `/api/entrants/${team.id}/decision`, { body: { approve: true } })

    const after = await call<{ entrants: { display_name: string }[] }>(
      'GET',
      `/api/contests/${spring}/entrants`,
      { query: { status: 'accepted' } },
    )
    expect(after.entrants.some((e) => e.display_name === 'Team Rocket')).toBe(true)
  })

  it('refuses the entrant list to a plain member of the organization', async () => {
    await signIn('carol@example.com')
    await expectFailure(
      () => call('GET', `/api/contests/${contestId('spring-oi')}/entrants`),
      403,
      'forbidden',
    )
  })

  it('refuses to reopen source visibility once registration has started', async () => {
    await signIn('alice@example.com')
    await expectFailure(
      () =>
        call('PATCH', `/api/contests/${contestId('spring-oi')}/source-public`, {
          body: { source_public_after: true },
        }),
      409,
      'conflict',
    )
  })
})

