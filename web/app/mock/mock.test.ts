describe('rejudge', () => {
  async function problemA(): Promise<{ id: string; problem_id: string }> {
    const res = await call<{ problems: { id: string; letter: string; problem_id: string }[] }>(
      'GET',
      `/api/contests/${contestId('winter-2026')}/problems`,
    )
    return res.problems.find((p) => p.letter === 'A')!
  }

  async function secondRevision(problemId: string): Promise<string> {
    const { revisions } = await call<{ revisions: { revision_id: string; revision_n: number }[] }>(
      'GET',
      `/api/problems/${problemId}/revisions`,
    )
    return revisions.find((r) => r.revision_n === 2)!.revision_id
  }

  it('keeps the old board until the batch is switched', async () => {
    await signIn('alice@example.com')
    const winter = contestId('winter-2026')
    const problem = await problemA()
    const target = await secondRevision(problem.problem_id)

    const before = await call<{ standings: StandingRow[] }>(
      'GET',
      `/api/contests/${winter}/standings`,
    )

    const batch = await call<{ batch_id: string; state: string }>(
      'POST',
      `/api/contest-problems/${problem.id}/rejudge`,
      { body: { revision_id: target } },
    )
    expect(batch.state).toBe('running')

    // Switching before the batch settles must be refused.
    await expectFailure(
      () => call('POST', `/api/rejudge-batches/${batch.batch_id}/switch`),
      409,
      'conflict',
    )

    const afterOpen = await call<{ standings: StandingRow[] }>(
      'GET',
      `/api/contests/${winter}/standings`,
    )
    expect(afterOpen.standings).toEqual(before.standings)

    const { pending_submissions } = await call<{ pending_submissions: string[] }>(
      'GET',
      '/api/_mock/state',
    )
    for (const id of pending_submissions) {
      await call('POST', `/api/_mock/judge/${id}/complete`)
    }

    const flagged = await call<{ submissions: Submission[] }>(
      'GET',
      `/api/contests/${winter}/submissions`,
      { query: { letter: 'A' } },
    )
    // Results now exist on the target revision, so they are not the scored ones.
    expect(flagged.submissions.some((s) => s.not_effective === true)).toBe(true)

    await call('POST', `/api/rejudge-batches/${batch.batch_id}/switch`)

    const settled = await call<{ submissions: Submission[] }>(
      'GET',
      `/api/contests/${winter}/submissions`,
      { query: { letter: 'A' } },
    )
    expect(settled.submissions.every((s) => s.not_effective !== true)).toBe(true)
  })

  it('rejects a second open batch for the same problem', async () => {
    await signIn('alice@example.com')
    const problem = await problemA()
    const target = await secondRevision(problem.problem_id)
    await call('POST', `/api/contest-problems/${problem.id}/rejudge`, {
      body: { revision_id: target },
    })
    await expectFailure(
      () =>
        call('POST', `/api/contest-problems/${problem.id}/rejudge`, {
          body: { revision_id: target },
        }),
      409,
      'conflict',
    )
  })

  it('refuses a rejudge to a plain member', async () => {
    await signIn('carol@example.com')
    const problem = await problemA()
    await expectFailure(
      () =>
        call('POST', `/api/contest-problems/${problem.id}/rejudge`, {
          body: { revision_id: 'whatever' },
        }),
      403,
      'forbidden',
    )
  })
})

