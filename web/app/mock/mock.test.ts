describe('standings', () => {
  async function standings(contest: string): Promise<StandingRow[]> {
    const res = await call<{ standings: StandingRow[] }>(
      'GET',
      `/api/contests/${contestId(contest)}/standings`,
    )
    return res.standings
  }

  it('scores an ACM contest by solves, then penalty, and reports pending work', async () => {
    await signIn('alice@example.com')
    const rows = await standings('winter-2026')

    expect(rows.map((r) => r.display_name)).toEqual([
      'Alice Chen',
      'Bob Liu',
      'Carol Wang',
      'Frank Wu',
    ])
    expect(rows.map((r) => r.rank)).toEqual([1, 2, 3, 4])

    const alice = rows[0]!
    // A: one wrong answer (+20) then AC at +12 ⇒ 32. B: AC at +25.
    expect(alice.solved).toBe(2)
    expect(alice.penalty_minutes).toBe(57)
    expect(alice.problems.map((p) => p.letter)).toEqual(['A', 'B', 'C'])
    expect(alice.problems[0]!.failed_attempts_before_ac).toBe(1)
    expect(alice.problems[0]!.solved).toBe(true)

    const bob = rows[1]!
    // A at +8; B: WA +20, TLE +30, AC +40 ⇒ 40 + 2×20 = 80.
    expect(bob.penalty_minutes).toBe(88)
    // C faulted on the system, so it stays pending and unsettles the row.
    expect(bob.unsettled).toBe(true)
    expect(bob.problems[2]!.pending).toBe(true)

    const carol = rows[2]!
    // A compile error does not count toward the ACM penalty.
    expect(carol.solved).toBe(1)
    expect(carol.penalty_minutes).toBe(30)
    expect(carol.problems[1]!.pending).toBe(true)
    expect(carol.problems[1]!.failed_attempts_before_ac).toBe(0)

    const frank = rows[3]!
    expect(frank.solved).toBe(0)
    expect(frank.total_score).toBe('0.00')
  })

  it('hides another entrant’s post-freeze solve from a non-administrator', async () => {
    // `intro-2026` ends in 25 minutes with a 60-minute freeze: it is frozen now.
    const intro = 'intro-2026'

    await signIn('dave@example.com') // organization owner ⇒ administrator view
    const adminDave = (await standings(intro)).find((r) => r.display_name === 'Dave Zhang')!
    expect(adminDave.solved).toBe(1)

    await signIn('erin@example.com') // plain member ⇒ frozen public view
    const frozenRows = await standings(intro)
    const frozenDave = frozenRows.find((r) => r.display_name === 'Dave Zhang')!
    expect(frozenDave.solved).toBe(0)
    expect(frozenDave.penalty_minutes).toBe(0)
    // The viewer keeps their own solve, and is re-ranked accordingly.
    const frozenErin = frozenRows.find((r) => r.display_name === 'Erin Zhao')!
    expect(frozenErin.solved).toBe(1)
    expect(frozenErin.rank).toBe(1)
  })

  it('refuses to show an unpublished OI scoreboard to a non-participant', async () => {
    // Frank is in no organization and is not registered for `spring-oi`, so he
    // is neither an administrator nor a contestant: the board stays hidden.
    await signIn('frank@example.com')
    await expectFailure(
      () => call('GET', `/api/contests/${contestId('spring-oi')}/standings`),
      403,
      'forbidden',
    )
  })

  it('gives a registered contestant their own rows while the board is hidden', async () => {
    // Bob's `spring-oi` team is accepted, so he is `self`: he gets his own row
    // instead of a 403, and nothing else.
    await signIn('bob@example.com')
    const rows = await standings('spring-oi')
    expect(rows.map((r) => r.display_name)).toEqual(['Null Pointer'])
  })

  it('gives an unaccepted entrant an empty board rather than a 403', async () => {
    // Dave's team is still awaiting review, so it is not scored at all.
    await signIn('dave@example.com')
    expect(await standings('spring-oi')).toEqual([])
  })
})

